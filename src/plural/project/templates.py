def resource_scaffold(
    kind: ResourceKind,
    name: str,
    *,
    environment: str | None = None,
    verifiers: tuple[str, ...] = (),
    model: str | None = None,
    harness: str | None = None,
    python: bool = False,
) -> Scaffold:
    """Files for ``plural <kind> init <name>``.

    An Environment starts as one App whose server is written with FastMCP;
    ``python=True`` starts it as a Python ``App`` class instead.

    Returns:
        The resource scaffold, relative to the resource directory.
    """
    cls = class_name(name)
    if kind is ENVIRONMENT and not python:
        app = name.replace("-", "_")
        return Scaffold(
            files={
                ENVIRONMENT.manifest: _MCP_ENVIRONMENT_YAML.format(name=name, app=app),
                "server.py": _MCP_SERVER_PY.format(title=title(name), app=app),
                "README.md": _MCP_ENVIRONMENT_README.format(title=title(name)),
            },
            directories=("resources",),
        )
    if kind is ENVIRONMENT:
        return Scaffold(
            files={
                ENVIRONMENT.manifest: _ENVIRONMENT_YAML.format(name=name, cls=cls),
                "environment.py": _ENVIRONMENT_PY.format(title=title(name), cls=cls),
                "README.md": _ENVIRONMENT_README.format(title=title(name)),
            },
            directories=("resources",),
        )
    if kind is TASK:
        environment_line = (
            f"environment: {environment}\n"
            if environment
            else "# PLURAL-TODO: name the one Environment this Task runs in.\n"
            "# environment: <environment-name>\n"
        )
        verifier_lines = (
            "verifiers:\n" + "".join(f"  - {item}\n" for item in verifiers)
            if verifiers
            else "# PLURAL-TODO: name at least one Verifier that scores this Task.\n"
            "# verifiers:\n#   - <verifier-name>\n"
        )
        return Scaffold(
            files={
                TASK.manifest: _TASK_YAML.format(
                    name=name, environment=environment_line, verifiers=verifier_lines
                ),
                "instruction.md": _TASK_INSTRUCTION.format(title=title(name)),
            },
            directories=("resources",),
        )
    if kind is VERIFIER:
        return Scaffold(
            files={
                VERIFIER.manifest: _VERIFIER_YAML.format(name=name),
                "verify.py": _VERIFIER_PY,
            }
        )
    if kind is HARNESS:
        return Scaffold(
            files={
                HARNESS.manifest: _HARNESS_YAML.format(name=name, cls=cls),
                "harness.py": _HARNESS_PY.format(cls=cls),
            }
        )
    if kind is AGENT:
        model_line = (
            f"model: {model}\n"
            if model
            else "# PLURAL-TODO: choose a model from `plural models list`.\n# model: <model-id>\n"
        )
        harness_line = (
            f"harness: {harness}\n"
            if harness
            else "# Optional: a built-in harness (claude-code, codex, hermes) or one in "
            "harnesses/.\n# harness: <harness-name>\n"
        )
        return Scaffold(
            files={
                AGENT.manifest: _AGENT_YAML.format(
                    name=name, model=model_line, harness=harness_line
                )
            }
        )
    if kind is BENCHMARK:
        return Scaffold(
            files={
                BENCHMARK.manifest: _BENCHMARK_YAML.format(name=name),
                "README.md": _BENCHMARK_README.format(title=title(name)),
            }
        )
    raise ValueError(f"no scaffold for {kind.name}")


