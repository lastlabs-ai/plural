@dataclass(frozen=True)
class Scaffold:
    """Files (path to text) and empty directories to create."""

    files: dict[str, str]
    directories: tuple[str, ...] = field(default_factory=tuple)

    def write(self, root: Path, *, overwrite: bool = False) -> list[Path]:
        """Create the scaffold under ``root``, skipping files that already exist.

        Returns:
            Paths that were written.
        """
        written = []
        for directory in self.directories:
            (root / directory).mkdir(parents=True, exist_ok=True)
        for relative, text in self.files.items():
            path = root / relative
            if path.exists() and not overwrite:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            written.append(path)
        return written


def class_name(name: str) -> str:
    """``support-desk`` -> ``SupportDesk``.

    Returns:
        The class name.
    """
    return "".join(part.capitalize() for part in name.replace("_", "-").split("-") if part)


def title(name: str) -> str:
    """``support-desk`` -> ``Support desk``.

    Returns:
        The title.
    """
    return name.replace("-", " ").capitalize()


MIN_SDK_VERSION = "0.21"
"""The oldest SDK that reads this project layout; new projects require it."""


def project_scaffold(name: str) -> Scaffold:
    """Files for ``plural project init``.

    Returns:
        The project scaffold.
    """
    return Scaffold(
        files={
            PROJECT_FILE: (
                "# Plural project identity. Resources live in the directories beside this file.\n"
                f"schema_version: {PROJECT_SCHEMA_VERSION}\n"
                f"name: {name}\n"
                'description: ""\n'
            ),
            LOCK_FILE: (
                "# Generated by Plural. Commit this file; do not edit it by hand.\n"
                "lock_version: 1\n"
                "resources: {}\n"
            ),
            "pyproject.toml": (
                "[project]\n"
                f'name = "{name}"\n'
                'version = "0.1.0"\n'
                'requires-python = ">=3.11"\n'
                f'dependencies = ["plural[mcp]>={MIN_SDK_VERSION}"]\n'
            ),
            "README.md": _PROJECT_README.format(name=name),
            ".gitignore": ".plural/\n__pycache__/\n.venv/\n",
        }
    )


