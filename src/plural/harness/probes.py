"""Probe Harnesses: fixed players that check a Task's graders before any Agent runs.

``plural task validate`` runs each probe through the normal engine, in the Task's own
Runtime, so what they find is what an Agent would meet:

- ``reference`` plays the Task's reference policy and must pass;
- ``noop`` answers nothing and must fail;
- ``echo`` answers with the Task's instructions and must fail;
- ``random`` takes random actions and must fail, when asked for.

``noop`` also lists what the Agent's sandbox exposes: each git repository with
history beyond its checked-out commit, and files named like a solution.
"""

from __future__ import annotations

import shutil
import tempfile
from collections.abc import Mapping
from pathlib import Path
from typing import Literal

import yaml

ProbeKind = Literal["reference", "noop", "echo", "random"]
PROBE_KINDS: tuple[ProbeKind, ...] = ("reference", "noop", "echo", "random")
SCAN_KEY = "plural_probe_scan"
"""Where the ``noop`` probe puts its workspace scan in its result's metadata."""

_PROBE_SOURCE = '''"""Plural's probe Harness. Generated by plural task validate; do not edit."""

import importlib.util
import json
import os
import random
import re
import subprocess
from pathlib import Path

from plural import Harness, HarnessResult

SUSPICIOUS = re.compile(r"^(solution|answer|reference)|\\.(orig|rej)$", re.IGNORECASE)
SKIPPED = {"proc", "sys", "dev", "usr", "lib", "lib64", "bin", "sbin", "etc", "var", "boot",
           "run", "opt", "srv", "snap", "node_modules", "__pycache__", ".venv", "site-packages"}
# Where images usually keep the code a Task works on. The host's own home folder is never
# scanned, since the local provider runs on it.
ROOTS = ("/workspace", "/testbed", "/repo", "/app", "/src", "/code", "/project")


class ProbeHarness(Harness):
    auth = ("none",)

    def run(self, task, agent, environment):
        kind = self.config["kind"]
        metadata = {}
        if kind == "noop":
            metadata["plural_probe_scan"] = scan([os.getcwd(), environment.workspace, *ROOTS])
            return HarnessResult(response="", metadata=metadata)
        if kind == "echo":
            environment.reset()
            return HarnessResult(response=task.instructions)
        if kind == "random":
            environment.reset()
            return HarnessResult(response=play_randomly(environment, int(self.config["steps"])))
        references = self.config["references"]
        reference = references.get(task.id) or references.get(task.name)
        if not reference:
            raise RuntimeError(f"Task {task.id or task.name} has no reference policy")
        path, _, name = reference.partition(":")
        source = Path(__file__).parent / path
        spec = importlib.util.spec_from_file_location("plural_reference", source)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return HarnessResult(response=getattr(module, name)(task, environment))


def play_randomly(environment, steps):
    rng = random.Random(0)
    actions = [item for item in environment.actions if item.get("name")]
    for _ in range(steps):
        if not actions:
            break
        action = rng.choice(actions)
        properties = (action.get("parameters") or {}).get("properties") or {}
        arguments = {name: sample(schema, rng) for name, schema in properties.items()}
        try:
            step = environment.step(action["name"], **arguments)
        except Exception:
            continue
        if step.done:
            break
    return ""


def sample(schema, rng):
    kind = schema.get("type")
    if schema.get("enum"):
        return rng.choice(schema["enum"])
    if kind == "integer":
        return rng.randint(1, 10)
    if kind == "number":
        return round(rng.uniform(1, 100), 2)
    if kind == "boolean":
        return rng.random() < 0.5
    if kind == "array":
        return []
    if kind == "object":
        return {}
    return "x"


def scan(roots, limit=2000):
    found = {"git": [], "suspicious": []}
    seen = 0
    for root in dict.fromkeys(item for item in roots if item and os.path.isdir(item)):
        for current, folders, files in os.walk(root):
            folders[:] = [name for name in folders if name not in SKIPPED]
            if ".git" in folders or ".git" in files:
                found["git"].append(git(current))
                folders[:] = [name for name in folders if name != ".git"]
            for name in files:
                seen += 1
                if SUSPICIOUS.search(name):
                    found["suspicious"].append(os.path.join(current, name))
            if seen > limit:
                found["truncated"] = True
                return found
    return found


def git(path):
    def run(*arguments):
        result = subprocess.run(
            ["git", "-c", "safe.directory=*", "-C", path, *arguments],
            capture_output=True,
            text=True,
            timeout=20,
        )
        if result.returncode != 0:
            raise RuntimeError((result.stderr or "git failed").strip().splitlines()[-1])
        return result.stdout.strip()

    try:
        commits = run("rev-list", "--all", "--count")
        tags = [line for line in run("tag").splitlines() if line]
        branches = [line.strip("* ").strip() for line in run("branch", "--all").splitlines()]
    except (OSError, RuntimeError, subprocess.SubprocessError) as exc:
        return {"path": path, "error": str(exc)}
    return {
        "path": path,
        "commits": int(commits) if commits.isdigit() else None,
        "tags": tags,
        "branches": [item for item in branches if item],
    }
'''


def probe_package(
    kind: ProbeKind,
    *,
    references: Mapping[str, Path] | None = None,
    random_steps: int = 20,
    directory: Path | None = None,
) -> Path:
    """Write one probe Harness package, ready for ``load_harness_directory``.

    Args:
        kind: Which probe.
        references: For ``reference``, each Task's reference as ``file.py:function``
            resolved to a file and function, keyed by Task name, such as
            ``{"quote-001": Path("environments/quoting/reference.py:solve")}``.
        random_steps: For ``random``, the actions to take.
        directory: Where to write it; a new temporary folder when left out.

    Returns:
        The package folder.

    Examples:
        >>> from plural.project.resources import load_harness_directory
        >>> load_harness_directory(probe_package("noop")).name
        'plural-probe-noop'
    """
    root = Path(directory or tempfile.mkdtemp(prefix=f"plural-probe-{kind}-"))
    root.mkdir(parents=True, exist_ok=True)
    (root / "probe.py").write_text(_PROBE_SOURCE, encoding="utf-8")
    mapping: dict[str, str] = {}
    copied: dict[Path, str] = {}
    for task, reference in sorted((references or {}).items()):
        source, _, function = str(reference).rpartition(":")
        path = Path(source).resolve()
        if path not in copied:
            copied[path] = f"reference_{len(copied)}.py"
            shutil.copyfile(path, root / copied[path])
        mapping[task] = f"{copied[path]}:{function}"
    manifest = {
        "name": f"plural-probe-{kind}",
        "version": "1.0.0",
        "description": f"Plural's {kind} probe for plural task validate.",
        "python": "probe.py:ProbeHarness",
        "config": {"kind": kind, "references": mapping, "steps": random_steps},
    }
    (root / "harness.yaml").write_text(yaml.safe_dump(manifest, sort_keys=False), "utf-8")
    return root


__all__ = ["PROBE_KINDS", "SCAN_KEY", "ProbeKind", "probe_package"]
